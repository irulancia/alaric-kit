// The component index in rules/common/design.md: every class the design system ships, grouped by the section of the
// stylesheet that defines it, so a session knows what exists without reading the full reference — and doesn't rebuild
// it. Generated from styles/components.css + styles/layouts.css (the same source as app.css), so it can't
// fall behind a new component: generate-components.js rewrites it, and the design system test fails if it differs.
const fs = require('fs');
const path = require('path');

const STYLES = path.join(__dirname, 'styles');
const DESIGN_MD = path.join(__dirname, '..', '..', 'rules', 'common', 'design.md');
const START = '<!-- component-index:start — generated by configurator/generate-components.js from the component styles; never edited by hand -->';
const END = '<!-- component-index:end -->';
const SECTION = /\/\* -{3,} (.+?) -{3,} \*\//;
const SKIP_SECTIONS = /^Mobile/;
// States and modifiers that only make sense on a component already listed (is-open, has-error…) aren't components.
const STATE = /^(is|has)-|^ds-root$/;

// The classes a rule styles are those of the last part of its selector that names one (`.badge .icon` styles an .icon,
// `.link.link-action` both, `.prose > * + *` a .prose).
function classesOf(part) {
  return (part.replace(/\([^)]*\)/g, '').match(/\.([a-z][a-z0-9-]*)/g) || []).map((c) => c.slice(1)).filter((c) => !STATE.test(c));
}

// Per selector: the classes of its last part that names one (what it styles), and every class it mentions.
function selectorClasses(css) {
  const selectors = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/@[a-z-]+[^{]*\{/g, '').match(/[^{}]+(?=\{)/g) || [];
  return selectors.flatMap((s) => s.split(',')).map((s) => {
    const parts = s.trim().split(/\s*[\s>+~]\s*/).map(classesOf).filter((c) => c.length);
    return { styled: parts.length ? parts[parts.length - 1] : [], all: parts.flat() };
  });
}

// Each class goes in the section that first styles it, since a stylesheet defines a component before its variants
// adjust it (.btn-primary is defined under Actions; the icon-style variants restyle it later). A class that is never
// styled itself (only a context, like .controls-duotone) goes where it first appears.
function homeSections(groups) {
  const home = {};
  const claim = (key) => (c, title) => { if (!home[c]) home[c] = { title, key }; };
  [['styled', claim('styled')], ['all', claim('all')]].forEach(([key, set]) => groups.forEach(([title, css]) => {
    selectorClasses(css).forEach((sel) => sel[key].forEach((c) => set(c, title)));
  }));
  return Object.fromEntries(Object.entries(home).map(([c, h]) => [c, h.title]));
}

function classesInOrder(css) {
  return selectorClasses(css).flatMap((sel) => [...sel.styled, ...sel.all]);
}

function sections(css, fallbackTitle) {
  const parts = css.split(new RegExp(SECTION.source));
  const list = parts[0].trim() && fallbackTitle ? [[fallbackTitle, parts[0]]] : [];
  for (let i = 1; i < parts.length; i += 2) list.push([parts[i].split(/[:(]/)[0].trim(), parts[i + 1]]);
  return list;
}

function buildIndex() {
  const read = (f) => fs.readFileSync(path.join(STYLES, f), 'utf8');
  const groups = [
    ...sections(read('components.css')),
    ['Page layouts', read('layouts.css')],
  ];
  const kept = groups.filter(([title]) => !SKIP_SECTIONS.test(title));
  const home = homeSections(kept);
  const seen = new Set();
  const lines = kept.map(([title, css]) => {
    const classes = classesInOrder(css).filter((c) => home[c] === title && !seen.has(c) && seen.add(c));
    return classes.length ? `- ${title}: ${classes.map((c) => `\`.${c}\``).join(' ')}` : '';
  }).filter(Boolean);
  return [START, ...lines, '- Icons: `.icon` + `.icon-<name>` (the names are the `.icon-*` rules at the end of `app.css`)', END].join('\n');
}

function currentIndex() {
  const md = fs.readFileSync(DESIGN_MD, 'utf8');
  const from = md.indexOf(START);
  const to = md.indexOf(END);
  return from < 0 || to < 0 ? null : md.slice(from, to + END.length);
}

function writeIndex() {
  const md = fs.readFileSync(DESIGN_MD, 'utf8');
  const current = currentIndex();
  if (current === null) throw new Error(`${DESIGN_MD} has no ${START.slice(0, 30)}… / ${END} markers to write the component index between.`);
  fs.writeFileSync(DESIGN_MD, md.replace(current, buildIndex()), 'utf8');
}

module.exports = { buildIndex, currentIndex, writeIndex, DESIGN_MD };

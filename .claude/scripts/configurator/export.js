// Export for the design system configurator: builds the CSS from the current choices and either
// saves it as a file (Chrome/Edge: save dialog that writes the file directly; other browsers:
// a download) or copies just the :root tokens. Loaded before the configurator's own script and
// reads its globals (state, computeTokens) only when a button is clicked.
(function () {
  const FONT_WEIGHTS = '400;500;600;700';
  const STATUS_CLEAR_MS = 4000;
  const COPIED_LABEL_MS = 1500;
  const CHOICES_CLASS = 'ds-saved-choices';
  const CHOICES_PROP = '--ds-choices';
  const PROJECT_APP_CSS = '../../../src/app.css';

  // The stylesheet requests for the chosen heading and body fonts. Also used for the live preview. Google Fonts takes
  // every family in one request; Fontshare gets ONE request per family — given two, its API returns only one of them
  // (found 2026-10-04: general-sans + switzer → General Sans alone).
  window.dsFontsUrls = () => {
    const chosen = [...new Set([state.fontDisplay, state.fontBody])];
    const google = chosen.filter((f) => !FONTSHARE_FONTS.includes(f));
    const fontshare = chosen.filter((f) => FONTSHARE_FONTS.includes(f));
    const urls = [];
    if (google.length) urls.push(`https://fonts.googleapis.com/css2?${google.map((f) => `family=${f.replace(/ /g, '+')}:wght@${FONT_WEIGHTS}`).join('&')}&display=swap`);
    fontshare.forEach((f) => urls.push(`https://api.fontshare.com/v2/css?f[]=${f.toLowerCase().replace(/ /g, '-')}@${FONT_WEIGHTS.replace(/;/g, ',')}&display=swap`));
    return urls;
  };

  const contrastRuleLabel = () => (state.contrast === 'wcag'
    ? 'WCAG 2 AA (4.5:1)'
    : 'APCA (may fall below WCAG 2 AA on mid-tones)');

  const controlsNote = () => (state.iconStyle !== 'filled' && state.styleControls
    ? `/* Buttons and pills: add class "controls-${state.iconStyle}" to the root element */\n`
    : '');

  const tokenBlock = () => ':root {\n'
    + Object.entries(computeTokens()).map(([k, v]) => `  ${k}: ${v};`).join('\n')
    + '\n}';

  // Just the tokens, with the note about the contrast rule that produced them.
  window.dsBuildTokensCss = () => `/* Button text contrast: ${contrastRuleLabel()} */\n${controlsNote()}${tokenBlock()}`;

  const header = () => `/* app.css: generated by the Design System Configurator (.claude/scripts/configurator/configurator.html).
   Do not edit by hand: change the choices in the configurator and save again.
   Choices: primary ${state.primary}, secondary ${state.secondary}, background ${state.customBg ? state.background : 'tinted from secondary'}, headings ${state.fontDisplay}, body ${state.fontBody},
   radius ${state.radius}px, shadow ${state.shadow}, density ${state.density}, icons ${state.iconStyle},
   button text contrast ${contrastRuleLabel()}.
   Usage: put class="ds-root" on <body>; element typography is scoped to it. */
${controlsNote()}`;

  // The choices, in the file itself, so the configurator opens with them in any browser (no element in a project has
  // this class: the rule does nothing there).
  const choicesRule = () => `/* The choices this file was saved with, read back by the configurator when it opens. */
.${CHOICES_CLASS} { ${CHOICES_PROP}: '${JSON.stringify(state)}'; }`;

  // The project's app.css: src/ beside .claude/, three folders up. A page opened as a file can't fetch() it, but it can
  // load it as a stylesheet — in a hidden frame, so its rules never touch this page — and read the choices from the
  // custom property above. found: there is an app.css; choices: null when it is older than that rule.
  window.dsReadProjectChoices = () => new Promise((resolve) => {
    const frame = document.createElement('iframe');
    frame.hidden = true;
    frame.srcdoc = `<link rel="stylesheet" href="${new URL(PROJECT_APP_CSS, location.href).href}"><span class="${CHOICES_CLASS}"></span>`;
    frame.addEventListener('load', () => {
      const doc = frame.contentDocument;
      const read = (el, prop) => doc.defaultView.getComputedStyle(el).getPropertyValue(prop).trim();
      const found = read(doc.documentElement, '--accent') !== '';
      const raw = read(doc.querySelector('span'), CHOICES_PROP);
      frame.remove();
      let choices = null;
      try { choices = raw ? JSON.parse(raw.slice(1, -1)) : null; } catch (e) { choices = null; }   // unreadable: treated as an older file
      resolve({ found, choices });
    });
    document.body.append(frame);
  });

  // The component styles come from configurator/components.generated.js (generated from the .css), loaded as a
  // script: a page opened as a file (file://) can't fetch() the .css next to it, but it can load a script.
  const readComponentsCss = () => {
    if (typeof window.DS_COMPONENTS_CSS !== 'string') {
      throw new Error('The component styles (configurator/components.generated.js) did not load. Run: node .claude/scripts/configurator/generate-components.js');
    }
    return window.DS_COMPONENTS_CSS;
  };

  // The icon set, in the chosen style, as CSS masks: <span class="icon icon-house" aria-hidden="true"></span>. The
  // icon is painted in currentColor, the duotone's tone at its own 20% (a mask reads the SVG's alpha). One file and
  // no framework needed — without it a project had no way to the icons and went digging through the configurator's
  // scripts for them (found 2026-10-15 by the kit's A/B evaluation). Inline <svg class="icon"> still works.
  const svgUrl = (paths) => `url("data:image/svg+xml,${`<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 256 256'>${paths.replace(/"/g, "'")}</svg>`
    .replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}")`;
  const iconsCss = () => {
    if (!window.DS_ICONS) throw new Error('The icons (configurator/icons.js) did not load.');
    const names = Object.keys(window.DS_ICONS).sort();
    return `/* Icons: Phosphor Icons (MIT, phosphoricons.com), ${state.iconStyle}, ${names.length} icons.
   Usage: <span class="icon icon-house" aria-hidden="true"></span> (sizes: .icon-sm, .icon-lg). An icon-only
   button still needs its aria-label. The names are the .icon-* rules below. */
span.icon { background-color: currentColor; -webkit-mask: var(--icon) center / contain no-repeat; mask: var(--icon) center / contain no-repeat; }
${names.map((n) => `.icon-${n} { --icon: ${svgUrl(window.DS_ICONS[n][state.iconStyle])}; }`).join('\n')}`;
  };

  window.dsBuildAppCss = async () => {
    const components = readComponentsCss();
    // @import must come before any rule, so it follows only the header comment.
    const imports = window.dsFontsUrls().map((u) => `@import url('${u}');\n`).join('');
    return `${header()}${imports}\n${tokenBlock()}\n\n${choicesRule()}\n\n${components.trim()}\n\n${iconsCss()}\n`;
  };

  const download = (css) => {
    const url = URL.createObjectURL(new Blob([css], { type: 'text/css' }));
    const a = document.createElement('a');
    a.href = url;
    a.download = 'app.css';
    document.body.append(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
  };

  // Returns what happened: 'saved', 'downloaded' or 'cancelled'.
  window.dsSaveAppCss = async () => {
    const css = await window.dsBuildAppCss();
    if (typeof window.showSaveFilePicker !== 'function') {
      download(css);
      return { result: 'downloaded', bytes: css.length };
    }
    let handle;
    try {
      handle = await window.showSaveFilePicker({ suggestedName: 'app.css', types: [{ description: 'CSS file', accept: { 'text/css': ['.css'] } }] });
    } catch (e) {
      if (e.name === 'AbortError') return { result: 'cancelled', bytes: 0 };
      throw e;
    }
    const writable = await handle.createWritable();
    await writable.write(css);
    await writable.close();
    return { result: 'saved', bytes: css.length };
  };

  const kb = (bytes) => `${Math.max(1, Math.round(bytes / 1024))} KB`;

  const setStatus = (text, isError) => {
    const el = document.getElementById('export-status');
    el.textContent = text;
    el.classList.toggle('error', Boolean(isError));
    clearTimeout(setStatus.timer);
    if (text && !isError) setStatus.timer = setTimeout(() => { el.textContent = ''; }, STATUS_CLEAR_MS);
  };

  const flash = (btn, doneLabel) => {
    const label = btn.dataset.label || btn.textContent;
    btn.dataset.label = label;
    btn.textContent = doneLabel;
    btn.classList.add('copied');
    setTimeout(() => { btn.textContent = label; btn.classList.remove('copied'); }, COPIED_LABEL_MS);
  };

  document.getElementById('save-btn').addEventListener('click', async (e) => {
    const btn = e.currentTarget;
    setStatus('');
    try {
      const { result, bytes } = await window.dsSaveAppCss();
      if (result === 'cancelled') return;
      if (result === 'saved') markSaved();   // what Reset goes back to now (ui.js)
      flash(btn, result === 'saved' ? 'Saved!' : 'Downloaded!');
      setStatus(result === 'saved'
        ? `Saved app.css (${kb(bytes)}).`
        : `Downloaded app.css (${kb(bytes)}). Move it into your project, for example src/app.css.`);
    } catch (err) {
      setStatus(`Could not save: ${err.message}`, true);
    }
  });

  document.getElementById('copy-btn').addEventListener('click', async (e) => {
    const btn = e.currentTarget; // null after an await, so keep it now
    setStatus('');
    try {
      await navigator.clipboard.writeText(window.dsBuildTokensCss());
      flash(btn, 'Copied!');
    } catch (err) {
      setStatus(`Could not copy: ${err.message}`, true);
    }
  });
})();
